// Look up a shade by hex (case-insensitive); null for custom colours.
export function findPaintColor(hex) {
  if (!hex) return null;
  const h = hex.toUpperCase();
  for (const c of PAINT_COLLECTIONS) {
    const color = c.colors.find((x) => x.hex.toUpperCase() === h);
    if (color) return { ...color, collection: c };
  }
  return null;
}
